def clean_name(value):
    """공백·괄호 안 설명을 제거해 비교하기 쉽게 만듦"""
    if pd.isna(value):
        return ""

    text = str(value).strip()
    text = re.sub(r"\([^)]*\)", "", text)
    text = re.sub(r"\s+", "", text)

    for word in [
        "고속버스터미널", "시외버스터미널", "공용버스터미널",
        "버스터미널", "버스정류장", "정류소", "매표소",
        "터미널", "정류장", "시외", "고속"
    ]:
        text = text.replace(word, "")

    return text.strip()

def assign_sigungu(value):
    """출발지명에서 강원 시군 추정"""
    raw = "" if pd.isna(value) else str(value).strip()
    cleaned = clean_name(raw)

    # 별칭부터 우선 매칭
    for keyword in sorted(aliases, key=len, reverse=True):
        if keyword in raw or keyword in cleaned:
            return pd.Series([aliases[keyword], "별칭 규칙"])

    # 출발지명에 시군 이름이 직접 들어간 경우
    for keyword in sorted(sigungu, key=len, reverse=True):
        if keyword in raw or keyword in cleaned:
            return pd.Series([sigungu[keyword], "시군명 포함"])

    # 이름만 보고 확정할 수 없는 경우
    return pd.Series(["미분류", "확인 필요"])

# 출발지 열이 있는지 검사
if "출발지" not in df.columns:
    raise ValueError(
        f"'출발지' 열을 찾지 못했습니다. 현재 열 이름: {df.columns.tolist()}"
    )

# 시군구 추정 열 생성
df[["시군구_추정", "분류근거"]] = df["출발지"].apply(assign_sigungu)

# 출발지별 중복 제거 매핑표
mapping = (
    df[["출발지", "시군구_추정", "분류근거"]]
    .drop_duplicates()
    .sort_values(["시군구_추정", "출발지"])
)

# 자동으로 못 붙인 출발지 목록
unmatched = mapping[mapping["시군구_추정"] == "미분류"].copy()

print("전체 고유 출발지 수:", len(mapping))
print("자동 분류된 출발지 수:", len(mapping) - len(unmatched))
