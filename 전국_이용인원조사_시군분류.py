# 6. 문자열 정리 함수
# ------------------------------------------------------------
def clean_name(value):
    if pd.isna(value):
        return ""

    text = str(value).strip()

    # 괄호 내용 제거: 예) 원주(시외) → 원주
    text = re.sub(r"\([^)]*\)", "", text)

    # 공백 제거
    text = re.sub(r"\s+", "", text)

    # 시설 유형 표현 제거
    remove_words = [
        "고속버스종합터미널",
        "시외버스종합터미널",
        "시외버스공용터미널",
        "공용버스터미널",
        "고속버스터미널",
        "시외버스터미널",
        "버스터미널",
        "버스정류장",
        "시외버스정류장",
        "공용버스정류장",
        "버스정류소",
        "정류소",
        "정류장",
        "매표소",
        "터미널",
        "시외",
        "고속",
    ]

    for word in remove_words:
        text = text.replace(word, "")

    return text.strip()


