def clean_name(value):
    """공백·괄호 안 설명을 제거해 비교하기 쉽게 만듦"""
    if pd.isna(value):
        return ""

    text = str(value).strip()
    text = re.sub(r"\([^)]*\)", "", text)
    text = re.sub(r"\s+", "", text)

    for word in [
        "고속버스터미널", "시외버스터미널", "공용버스터미널",
        "버스터미널", "버스정류장", "정류소", "매표소",
        "터미널", "정류장", "시외", "고속"
    ]:
        text = text.replace(word, "")

    return text.strip()

def assign_sigungu(value):
    """출발지명에서 경남 시군 추정"""
    raw = "" if pd.isna(value) else str(value).strip()
    cleaned = clean_name(raw)

    # 별칭부터 우선 매칭
    for keyword in sorted(aliases, key=len, reverse=True):
        if keyword in raw or keyword in cleaned:
            return pd.Series([aliases[keyword], "별칭 규칙"])

    # 출발지명에 시군 이름이 직접 들어간 경우
    for keyword in sorted(sigungu, key=len, reverse=True):
        if keyword in raw or keyword in cleaned:
            return pd.Series([sigungu[keyword], "시군명 포함"])

    # 이름만 보고 확정할 수 없는 경우
    return pd.Series(["미분류", "확인 필요"])

