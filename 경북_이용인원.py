from google.colab import files
import pandas as pd
import re

# =====================================================
# 1. 파일 4개 업로드: 2021, 2022, 2023, 2024 철도 파일
# =====================================================
uploaded = files.upload()

# =====================================================
# 2. 엑셀에서 실제 표 제목 행을 자동으로 찾는 함수
# =====================================================
def read_rail_file(file_name):
    raw = pd.read_excel(file_name, sheet_name=0, header=None)

    header_row = None

    for i in range(len(raw)):
        row = raw.iloc[i].astype(str).str.strip().tolist()

        if "시/도" in row and "출발지" in row and "도착지" in row:
            header_row = i
            break

    if header_row is None:
        raise ValueError(
            f"'{file_name}'에서 '시/도·출발지·도착지'가 있는 제목 행을 찾지 못했습니다."
        )

    data = pd.read_excel(file_name, sheet_name=0, header=header_row)
    data.columns = data.columns.astype(str).str.strip()
    data = data.dropna(how="all").reset_index(drop=True)

    return data

# =====================================================
# 3. 2021~2024 파일을 읽고 하나로 합치기
# =====================================================
all_data = []

for file_name in uploaded.keys():
    year_match = re.search(r"(2021|2022|2023|2024)", file_name)

    if year_match is None:
        print("파일명에 연도가 없어 제외함:", file_name)
        continue

    year = int(year_match.group(1))
    temp = read_rail_file(file_name)
    temp["연도"] = year

    all_data.append(temp)

if len(all_data) == 0:
    raise ValueError("파일명에 2021, 2022, 2023, 2024가 포함된 엑셀 파일을 업로드하세요.")

df = pd.concat(all_data, ignore_index=True)

# =====================================================
# 4. 월~일 값을 숫자로 변경
# =====================================================
weekday_cols = ["월", "화", "수", "목", "금", "토", "일"]

for col in weekday_cols:
    df[col] = (
        df[col]
        .astype(str)
        .str.replace(",", "", regex=False)
        .str.strip()
    )

    df[col] = pd.to_numeric(df[col], errors="coerce").fillna(0)

# =====================================================
# 5. 경북 출발 → 서울·용산·수서·청량리 도착만 남기기
# =====================================================
target_stations = ["서울", "용산", "수서", "청량리"]

df["시/도"] = df["시/도"].astype(str).str.strip()
df["출발지"] = df["출발지"].astype(str).str.strip()
df["도착지"] = df["도착지"].astype(str).str.strip()

filtered = df[
    (df["시/도"] == "경상북도") &
    (df["도착지"].isin(target_stations))
].copy()

# =====================================================
# 6. 월~일 합계 열 만들기
# =====================================================
filtered["월~일합계"] = filtered[weekday_cols].sum(axis=1)

# =====================================================
# 7. 세 종류의 결과표 생성
# =====================================================

# ① 출발역별·도착역별·연도별 결과
detail_result = filtered[
    ["연도", "시/도", "ID", "출발지", "도착지"] +
    weekday_cols +
    ["월~일합계"]
].copy()

# ② 경북 전체 출발역을 합산한 연도별·도착역별 결과
station_result = (
    filtered
    .groupby(["연도", "도착지"], as_index=False)["월~일합계"]
    .sum()
    .sort_values(["연도", "도착지"])
)

# ③ 서울·용산·수서·청량리를 모두 합친 연도별 총합
year_result = (
    filtered
    .groupby("연도", as_index=False)["월~일합계"]
    .sum()
    .rename(columns={"월~일합계": "서울4개역_월~일합계"})
    .sort_values("연도")
)

# =====================================================
# 8. 결과를 엑셀 파일 1개로 저장
# =====================================================
output_file = "경북_철도_서울용산수서청량리_2021_2024_결과.xlsx"

with pd.ExcelWriter(output_file, engine="openpyxl") as writer:
    detail_result.to_excel(writer, sheet_name="상세결과", index=False)
    station_result.to_excel(writer, sheet_name="연도_도착역별합계", index=False)
    year_result.to_excel(writer, sheet_name="연도별_4개역전체합계", index=False)

# =====================================================
# 9. 결과 확인 및 다운로드
# =====================================================
print("완료")
print("실제로 찾아진 도착역:", sorted(filtered["도착지"].unique()))
print("\n연도별 서울 4개 역 전체 합계:")
display(year_result)

files.download(output_file)

