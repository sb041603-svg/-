# 5. 만족도 자료 ----------------------------------------------

만족도읽기 <- function(파일, 시도명) {
  x <- read_excel(
    파일,
    sheet = "요약_불만족보통만족"
  )
  
  필수열 <- c("시군", "순만족도(%)")
  
  if (!all(필수열 %in% names(x))) {
    stop("만족도 자료에 필요한 열이 없습니다: ", basename(파일))
  }
  
  x %>%
    transmute(
      시도 = 시도명,
      시군구 = 이름정리(시군),
      시외고속_순만족도 = 숫자변환(`순만족도(%)`)
    ) %>%
    distinct(시도, 시군구, .keep_all = TRUE)
}

만족도 <- bind_rows(
  만족도읽기(전북만족도파일, "전북"),
  만족도읽기(전남만족도파일, "전남")
)

