# 7. GTFS 자료 ------------------------------------------------
# 실제 확인된 열 이름 사용:
# 분석연도, 도, 출발시군, 교통수단,
# route_id기준_노선수, 직접서울행_운행회차수

gtfs시트목록 <- excel_sheets(GTFS파일)

if (!"연도별 지역요약" %in% gtfs시트목록) {
  stop("GTFS 파일에 '연도별 지역요약' 시트가 없습니다.")
}

gtfs원본 <- read_excel(
  GTFS파일,
  sheet = "연도별 지역요약"
)

필수GTFS열 <- c(
  "분석연도",
  "도",
  "출발시군",
  "교통수단",
  "route_id기준_노선수",
  "직접서울행_운행회차수"
)

if (!all(필수GTFS열 %in% names(gtfs원본))) {
  stop(
    "GTFS 필수 열 확인 필요: ",
    paste(setdiff(필수GTFS열, names(gtfs원본)), collapse = ", ")
  )
}

gtfs정리 <- gtfs원본 %>%
  transmute(
    연도 = 숫자변환(분석연도),
    도 = as.character(도),
    시군구 = 이름정리(출발시군),
    교통수단 = as.character(교통수단),
    서울직행노선수 = 숫자변환(route_id기준_노선수),
    서울직행운행횟수 = 숫자변환(직접서울행_운행회차수)
  ) %>%
  filter(
    str_detect(도, "전북|전라북도|전남|전라남도"),
    시군구 %in% 지역$시군구,
    연도 %in% c(2024, 2025)
  )

if (nrow(gtfs정리) == 0) {
  stop(
    "GTFS 지역 필터 결과가 0행입니다. ",
    "도·출발시군 값과 요약 시트 구조를 확인하십시오."
  )
}

# 노선수는 지역·연도별로 고유 노선 수를 집계합니다.
# 운행횟수는 확인된 직접서울행 운행회차수를 합산합니다.

gtfs집계 <- gtfs정리 %>%
  group_by(도, 시군구, 연도) %>%
  summarise(
    서울직행노선수 = sum(서울직행노선수, na.rm = TRUE),
    서울직행운행횟수 = sum(서울직행운행횟수, na.rm = TRUE),
    .groups = "drop"
  ) %>%
  mutate(
    시도 = case_when(
      str_detect(도, "전북|전라북도") ~ "전북",
      str_detect(도, "전남|전라남도") ~ "전남",
      TRUE ~ NA_character_
    )
  )

# 2024·2025년 지표를 열로 변환

gtfs증감 <- gtfs집계 %>%
  select(
    시도, 시군구, 연도,
    서울직행노선수, 서울직행운행횟수
  ) %>%
  pivot_wider(
    names_from = 연도,
    values_from = c(서울직행노선수, 서울직행운행횟수),
    names_glue = "{.value}_{연도}"
  )

필요연도열 <- c(
  "서울직행노선수_2024",
  "서울직행노선수_2025",
  "서울직행운행횟수_2024",
  "서울직행운행횟수_2025"
)

for (nm in 필요연도열) {
  if (!nm %in% names(gtfs증감)) {
    gtfs증감[[nm]] <- NA_real_
  }
}

gtfs증감 <- gtfs증감 %>%
  mutate(
    서울직행_노선수증감률 = if_else(
      !is.na(서울직행노선수_2024) &
        서울직행노선수_2024 > 0 &
        !is.na(서울직행노선수_2025),
      (서울직행노선수_2025 - 서울직행노선수_2024) /
        서울직행노선수_2024 * 100,
      NA_real_
    ),
    서울직행_운행횟수증감률 = if_else(
      !is.na(서울직행운행횟수_2024) &
        서울직행운행횟수_2024 > 0 &
        !is.na(서울직행운행횟수_2025),
      (서울직행운행횟수_2025 - 서울직행운행횟수_2024) /
        서울직행운행횟수_2024 * 100,
      NA_real_
    )
  )

# 8. 최종 통합 ------------------------------------------------

최종 <- 지역 %>%
  left_join(
    인구정리 %>%
      select(
        시도, 시군구,
        전체인구, 노인인구, 장애인구,
        전체자가용수, 자가용승용차수,
        노인비율, 장애인비율,
        자동차등록대수_인구천명당
      ),
    by = c("시도", "시군구")
  ) %>%
  left_join(
    만족도,
    by = c("시도", "시군구")
  ) %>%
  left_join(
    이용인원지표,
    by = c("시도", "시군구")
  ) %>%
  left_join(
    gtfs증감 %>%
      select(
        시도, 시군구,
        서울직행노선수_2024,
        서울직행노선수_2025,
        서울직행운행횟수_2024,
        서울직행운행횟수_2025,
        서울직행_노선수증감률,
        서울직행_운행횟수증감률
      ),
    by = c("시도", "시군구")
  ) %>%
  mutate(
    서울직행노선수_인구10만명당 = if_else(
      전체인구 > 0,
      서울직행노선수_2024 / 전체인구 * 100000,
      NA_real_
    ),
    서울직행운행횟수_인구10만명당 = if_else(
      전체인구 > 0,
      서울직행운행횟수_2024 / 전체인구 * 100000,
      NA_real_
    )
  ) %>%
  arrange(
    factor(시도, levels = c("전북", "전남")),
    시군구
  )

