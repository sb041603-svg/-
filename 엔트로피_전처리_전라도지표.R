# 2. 공통 함수 ------------------------------------------------

숫자변환 <- function(x) {
  suppressWarnings(
    as.numeric(gsub(",", "", as.character(x), fixed = TRUE))
  )
}

이름정리 <- function(x) {
  x <- as.character(x)
  x <- str_trim(x)
  x <- str_replace_all(x, "\\s+", "")
  x <- str_replace_all(x, "\\(.*?\\)", "")
  x <- str_replace_all(x, "\\[.*?\\]", "")
  
  x <- str_replace(x, "전북특별자치도", "")
  x <- str_replace(x, "전라북도", "")
  x <- str_replace(x, "전라남도", "")
  
  x <- str_replace(x, "전주시완산구|전주시덕진구", "전주시")
  x <- str_replace(x, "군산시", "군산시")
  x <- str_replace(x, "익산시", "익산시")
  
  x
}

# 3. 인구·장애인·자동차 자료 -------------------------------
# 확인된 구조:
# 1열: 시도/시군구
# 2열: 시군구명
# 3~9열: 2020
# 10~16열: 2021
# 17~23열: 2022
# 24~30열: 2023
# 31~37열: 2024
#
# 각 연도 항목:
# 전체 장애인 수, 심한 장애인 수, 심하지 않은 장애인 수,
# 전체 자가용 수, 자가용 승용차 수, 65세 이상 인구 수,
# 전체 등록인구 수

인구원본 <- read_excel(
  인구파일,
  sheet = "전체_보기",
  col_names = FALSE,
  .name_repair = "minimal"
)

if (ncol(인구원본) < 37) {
  stop("인구자료의 열 수가 예상한 37개보다 적습니다.")
}

인구원본 <- as.data.frame(인구원본)
인구원본 <- 인구원본[-c(1, 2), , drop = FALSE]

names(인구원본) <- paste0("열", seq_len(ncol(인구원본)))

인구정리 <- 인구원본 %>%
  mutate(
    시도원본 = as.character(열1),
    시군구원본 = as.character(열2)
  ) %>%
  mutate(
    시도원본 = na_if(str_trim(시도원본), ""),
    시도원본 = tidyr::fill(
      data.frame(시도원본 = 시도원본),
      시도원본,
      .direction = "down"
    )$시도원본
  ) %>%
  mutate(
    시도 = case_when(
      str_detect(시도원본, "전북|전라북도") ~ "전북",
      str_detect(시도원본, "전남|전라남도") ~ "전남",
      TRUE ~ NA_character_
    ),
    시군구 = 이름정리(시군구원본),
    
    장애인구 = 숫자변환(열31),
    심한장애인구 = 숫자변환(열32),
    심하지않은장애인구 = 숫자변환(열33),
    전체자가용수 = 숫자변환(열34),
    자가용승용차수 = 숫자변환(열35),
    노인인구 = 숫자변환(열36),
    전체인구 = 숫자변환(열37)
  ) %>%
  filter(
    !is.na(시도),
    !is.na(시군구),
    시군구 != "",
    시군구 != "전체"
  ) %>%
  group_by(시도, 시군구) %>%
  summarise(
    across(
      c(
        장애인구, 심한장애인구, 심하지않은장애인구,
        전체자가용수, 자가용승용차수, 노인인구, 전체인구
      ),
      ~ {
        v <- .x[!is.na(.x)]
        if (length(v) == 0) NA_real_ else v[1]
      }
    ),
    .groups = "drop"
  ) %>%
  mutate(
    노인비율 = if_else(
      전체인구 > 0,
      노인인구 / 전체인구 * 100,
      NA_real_
    ),
    장애인비율 = if_else(
      전체인구 > 0,
      장애인구 / 전체인구 * 100,
      NA_real_
    ),
    자동차등록대수_인구천명당 = if_else(
      전체인구 > 0,
      전체자가용수 / 전체인구 * 1000,
      NA_real_
    )
  )

