def clean_text(value):

    if pd.isna(value):
        return ""

    return (
        str(value)
        .replace("\n", "")
        .replace("\r", "")
        .replace(" ", "")
        .replace("\u3000", "")
        .strip()
    )


def to_number(value):

    if pd.isna(value):
        return np.nan

    if isinstance(value, str):

        value = value.strip()

        if value in [
            "",
            "-",
            "–",
            "—"
        ]:
            return np.nan

        value = (
            value
            .replace(",", "")
            .replace("%", "")
            .replace("점", "")
        )

    return pd.to_numeric(
        value,
        errors="coerce"
    )


