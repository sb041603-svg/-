def to_number(value):

    if pd.isna(value):
        return np.nan

    if isinstance(value, str):

        value = value.strip()

        if value in [
            "",
            "-",
            "–",
            "—",
            "해당없음",
            "해당 없음"
        ]:
            return np.nan

        value = (
            value
            .replace(",", "")
            .replace("%", "")
            .replace("점", "")
        )

    return pd.to_numeric(
        value,
        errors="coerce"
    )


def clean_text(value):

    if pd.isna(value):
        return ""

    return (
        str(value)
        .replace("\n", "")
        .replace("\r", "")
        .replace(" ", "")
        .replace("　", "")
        .strip()
    )


