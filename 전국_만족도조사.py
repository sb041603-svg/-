import io
import re
import numpy as np
import pandas as pd
from google.colab import files
from IPython.display import display

# 1. 원자료 업로드
uploaded = files.upload()

if len(uploaded) == 0:
    raise ValueError("엑셀 파일이 업로드되지 않았습니다.")

input_name = next(iter(uploaded))
input_bytes = uploaded[input_name]

print("업로드 파일:", input_name)

# 2. 엑셀 파일 읽기
excel = pd.ExcelFile(io.BytesIO(input_bytes))
print("시트 목록:", excel.sheet_names)

data_sheet = "데이터" if "데이터" in excel.sheet_names else excel.sheet_names[0]
raw = pd.read_excel(
    io.BytesIO(input_bytes),
    sheet_name=data_sheet,
    header=None
)

if raw.shape[0] < 4 or raw.shape[1] < 3:
    raise ValueError("엑셀 파일의 행·열 구조를 확인할 수 없습니다.")

# 3. 시외·고속버스 열 찾기
transport_row = raw.iloc[1].astype(str)
measure_row = raw.iloc[2].astype(str)

target_cols = [
    i for i, value in transport_row.items()
    if "시외" in value and "고속" in value and "버스" in value
]

if not target_cols:
    raise ValueError("시외·고속버스 열을 찾지 못했습니다.")

print("시외·고속버스 열:", target_cols)

# 4. 시외·고속버스 세부 항목 분류
column_map = {}

for i in target_cols:
    measure = str(measure_row.iloc[i]).strip()

    if "매우 불만족" in measure:
        key = "매_불"
    elif "약간 불만족" in measure:
        key = "약_불"
    elif measure.startswith("보통"):
        key = "보통"
    elif "약간 만족" in measure:
        key = "약_만"
    elif "매우 만족" in measure:
        key = "매_만"
    elif "해당없음" in measure or "해당 없음" in measure:
        key = "해당없음"
    elif "5점 평균" in measure:
        key = "5점평균"
    else:
        continue

    column_map[i] = key

print("분류된 열:", column_map)

# 5. 시군별 구간 찾기
category_col = raw.iloc[:, 0].astype(str).str.strip()

start_candidates = raw.index[category_col.eq("시군별")]

if len(start_candidates) == 0:
    raise ValueError("시군별 구간을 찾지 못했습니다.")

start = start_candidates[0]

end_categories = [
    "성별",
    "연령별",
    "교육정도별",
    "혼인상태별",
    "주택유형별",
    "주거점유형태별",
    "가구소득별",
    "세대구분별",
    "직업별"
]

end_candidates = raw.index[
    (raw.index > start) & category_col.isin(end_categories)
]

end = end_candidates[0] if len(end_candidates) else len(raw)

# 중요:
# 춘천시는 '시군별'이라는 행에 이미 들어 있으므로
# start + 1이 아니라 start부터 읽어야 합니다.
rows = []

for _, row in raw.iloc[start:end].iterrows():

    region = row.iloc[1]

    if pd.isna(region):
        continue

    region = str(region).strip()

    if region in ["", "nan", "소계"]:
        continue

    record = {
        "시도": "자동입력_확인필요",
        "시군": region
    }

    for col_index, key in column_map.items():

        value = row.iloc[col_index]

        if isinstance(value, str):
            value = value.strip()

            if value in ["", "-", "–", "—"]:
                value = np.nan

        record[key] = pd.to_numeric(value, errors="coerce")

    rows.append(record)

if len(rows) == 0:
    raise ValueError("시군별 데이터를 추출하지 못했습니다.")

df = pd.DataFrame(rows)

# 6. 시도명 자동 입력
province_candidates = {
    "강원": "강원특별자치도",
    "경기": "경기도",
    "충북": "충청북도",
    "충남": "충청남도",
    "전북": "전북특별자치도",
    "전남": "전라남도",
    "경북": "경상북도",
    "경남": "경상남도",
    "제주": "제주특별자치도"
}

province = None

for keyword, name in province_candidates.items():
    if keyword in input_name:
        province = name
        break

if province is None:
    province = input_name.rsplit(".", 1)[0]

df["시도"] = province

# 7. 필요한 원자료 열 생성
raw_cols = [
    "매_불",
    "약_불",
    "보통",
    "약_만",
    "매_만",
    "해당없음"
]

for col in raw_cols:

    if col not in df.columns:
        df[col] = np.nan

    df[col] = pd.to_numeric(
        df[col],
        errors="coerce"
    )

# 8. 해당없음 및 유효응답 계산
# 해당없음이 숫자인 경우에만 유효응답 기준으로 환산
# 해당없음이 '-' 또는 결측이면 0으로 처리하지 않음

df["유효응답비율(%)"] = 100 - df["해당없음"]

for col in [
    "매_불",
    "약_불",
    "보통",
    "약_만",
    "매_만"
]:

    df[f"{col}(유효)"] = np.where(
        df["해당없음"].notna()
        & (df["유효응답비율(%)"] > 0),
        df[col] / df["유효응답비율(%)"] * 100,
        np.nan
    )

# 9. 시트 1: 응답별 유효응답
valid_sheet = df[
    [
        "시도",
        "시군",
        "매_불(유효)",
        "약_불(유효)",
        "보통(유효)",
        "약_만(유효)",
        "매_만(유효)",
        "해당없음",
        "유효응답비율(%)"
    ]
].copy()

valid_sheet = valid_sheet.rename(
    columns={
        "해당없음": "해당없음비율(%)"
    }
)

valid_sheet["산출기준"] = np.where(
    valid_sheet["해당없음비율(%)"].notna(),
    "해당없음 제외 후 유효응답 기준",
    "해당없음 미제공: 유효응답 환산 불가"
)

valid_sheet["주의사항"] = np.where(
    valid_sheet["해당없음비율(%)"].notna(),
    "해당없음은 만족·불만족에 포함하지 않음",
    "해당없음 결측으로 유효응답 환산값이 없음"
)

# 유효응답 환산이 불가능한 지역의 원자료 비율 보존
for col in [
    "매_불",
    "약_불",
    "보통",
    "약_만",
    "매_만"
]:

    valid_sheet[f"{col}(원자료)"] = df[col]

# 10. 시트 2: 불만족·보통·만족 요약
summary = df[
    [
        "시도",
        "시군"
    ]
].copy()

summary["불만족비율(유효)"] = (
    df["매_불(유효)"]
    + df["약_불(유효)"]
)

summary["보통비율(유효)"] = df["보통(유효)"]

summary["만족비율(유효)"] = (
    df["약_만(유효)"]
    + df["매_만(유효)"]
)

summary["해당없음비율(%)"] = df["해당없음"]
summary["유효응답비율(%)"] = df["유효응답비율(%)"]

summary["산출기준"] = np.where(
    df["해당없음"].notna(),
    "해당없음 제외 후 유효응답 기준",
    "해당없음 미제공: 유효응답 환산 불가"
)

# 11. 검산 시트
check = df[
    [
        "시도",
        "시군",
        "해당없음",
        "유효응답비율(%)"
    ]
].copy()

check = check.rename(
    columns={
        "해당없음": "해당없음비율(%)"
    }
)

check["유효 5개 범주 합계"] = (
    df["매_불(유효)"]
    + df["약_불(유효)"]
    + df["보통(유효)"]
    + df["약_만(유효)"]
    + df["매_만(유효)"]
)

check["검산차이"] = (
    check["유효 5개 범주 합계"] - 100
)

check["검산상태"] = np.where(
    check["유효 5개 범주 합계"].isna(),
    "유효응답 환산 불가",
    np.where(
        check["검산차이"].abs() <= 0.2,
        "정상",
        "확인 필요"
    )
)

# 12. 처리 기준 시트
rules = pd.DataFrame(
    {
        "항목": [
            "대상 교통수단",
            "대상 지역단위",
            "유효응답비율",
            "응답별 유효비율",
            "불만족비율",
            "만족비율",
            "해당없음 처리",
            "해당없음 결측 처리",
            "5점 평균 처리"
        ],
        "내용": [
            "시외·고속버스",
            "시군별",
            "100 - 해당없음 비율",
            "원자료 응답비율 ÷ 유효응답비율 × 100",
            "매우 불만족 + 약간 불만족",
            "약간 만족 + 매우 만족",
            "만족·불만족에 포함하지 않고 분모에서 제외",
            "0%로 임의 처리하지 않고 유효응답 환산값은 결측 처리",
            "지역별 결측 가능성이 있어 분석지표에서 제외"
        ]
    }
)

# 13. 숫자 반올림
for table in [
    valid_sheet,
    summary,
    check
]:

    numeric_cols = table.select_dtypes(
        include="number"
    ).columns

    table[numeric_cols] = table[numeric_cols].round(2)

# 14. 결과 엑셀 저장
safe_name = re.sub(
    r"[^가-힣A-Za-z0-9_-]",
    "_",
    input_name.rsplit(".", 1)[0]
)

output_name = (
    f"{safe_name}_시외고속버스_시군별_전처리.xlsx"
)

with pd.ExcelWriter(
    output_name,
    engine="openpyxl"
) as writer:

    valid_sheet.to_excel(
        writer,
        sheet_name="응답별_유효응답",
        index=False
    )

    summary.to_excel(
        writer,
        sheet_name="요약_불만족보통만족",
        index=False
    )

    check.to_excel(
        writer,
        sheet_name="검산",
        index=False
    )

    rules.to_excel(
        writer,
        sheet_name="처리기준",
        index=False
    )

# 15. 결과 확인
print()
print("추출된 시군 수:", len(df))
print("추출된 시군 목록:")
print(df["시군"].tolist())

if "춘천시" in df["시군"].tolist():
    print()
    print("춘천시가 정상적으로 포함되었습니다.")
else:
    raise ValueError(
        "춘천시가 추출되지 않았습니다."
    )

print()
print("최종 요약표:")
display(summary)

# 16. 결과 파일 다운로드
files.download(output_name)

