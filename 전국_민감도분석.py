# 7. TOPSIS 계산 함수
# ----------------------------------------------------------
def run_topsis(missing_weight):

    weighted_matrix = T_normalized[indicator_names].copy()

    for col in indicator_names:
        weight = np.where(
            S[col] == 2,
            missing_weight,
            1.0
        )

        weighted_matrix[col] = (
            T_normalized[col] *
            weight *
            final_weights[col]
        )

    ideal_best = weighted_matrix[indicator_names].max()
    ideal_worst = weighted_matrix[indicator_names].min()

    distance_best = np.sqrt(
        ((weighted_matrix[indicator_names] - ideal_best) ** 2).sum(axis=1)
    )

    distance_worst = np.sqrt(
        ((weighted_matrix[indicator_names] - ideal_worst) ** 2).sum(axis=1)
    )

    closeness = distance_worst / (
        distance_best + distance_worst
    )

    result = pd.DataFrame({
        "도": T["도"],
        "시군구": T["시군구"],
        "취약도_CC": closeness
    })

    result = result.sort_values(
        "취약도_CC",
        ascending=False
    ).reset_index(drop=True)

    result["순위"] = result.index + 1

    return result

