def calculate_entropy_weights():

    final_weights = {}
    entropy_rows = []

    for category, cols in categories.items():

        category_total = category_weights[category]

        diversity_values = {}
        internal_weights = {}

        for col in cols:
            x = E[col].astype(float).dropna()

            if len(x) < 2:
                diversity_values[col] = 0.0
                internal_weights[col] = 0.0
                continue

            p = x / x.sum()
            p = p.replace(0, 1e-12)

            n = len(x)
            k = 1 / np.log(n)

            entropy = -(p * np.log(p)).sum() * k
            diversity = 1 - entropy

            diversity_values[col] = diversity

        diversity_sum = sum(diversity_values.values())

        if diversity_sum == 0:
            for col in cols:
                internal_weights[col] = 1 / len(cols)
        else:
            for col in cols:
                internal_weights[col] = (
                    diversity_values[col] / diversity_sum
                )

        category_final = {
            col: internal_weights[col] * category_total
            for col in cols
        }

        if CAR_INDICATOR in cols:
            car_weight = category_final[CAR_INDICATOR]

            if car_weight > CAR_CAP_TOTAL:
                excess = car_weight - CAR_CAP_TOTAL
                category_final[CAR_INDICATOR] = CAR_CAP_TOTAL

                others = [
                    c for c in cols
                    if c != CAR_INDICATOR
                ]

                other_sum = sum(category_final[c] for c in others)

                for c in others:
                    category_final[c] += (
                        excess * category_final[c] / other_sum
                    )

        for col in cols:
            final_weights[col] = category_final[col]

            entropy_rows.append({
                "대분류": category,
                "지표명": col,
                "유효표본수": E[col].notna().sum(),
                "다양성": diversity_values[col],
                "대분류내부가중치": internal_weights[col],
                "최종가중치": category_final[col]
            })

    return pd.DataFrame(entropy_rows), final_weights

# ----------------------------------------------------------
# 7. TOPSIS 계산 함수
