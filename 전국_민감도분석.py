# ----------------------------------------------------------
# 6. 엔트로피 가중치 계산 함수
# ----------------------------------------------------------
def calculate_entropy_weights(include_bus, include_rail):

    final_weights = {}
    entropy_rows = []

    for category, cols in categories.items():

        # 전체 노선수는 모든 시나리오에서 제외
        cols = [
            col for col in cols
            if col != TOTAL_ROUTE
        ]

        # 노선수 시나리오 적용
        if category == "B_교통쇠퇴":
            if not include_bus:
                cols = [
                    col for col in cols
                    if col != BUS_ROUTE
                ]

            if not include_rail:
                cols = [
                    col for col in cols
                    if col != RAIL_ROUTE
                ]

        category_total = category_weights[category]

        diversity_values = {}
        internal_weights = {}

        for col in cols:
            x = E[col].astype(float).dropna()

            if len(x) < 2:
                diversity_values[col] = 0.0
                internal_weights[col] = 0.0
                continue

            p = x / x.sum()
            p = p.replace(0, 1e-12)

            n = len(x)
            k = 1 / np.log(n)

            entropy = -(p * np.log(p)).sum() * k
            diversity = 1 - entropy

            diversity_values[col] = diversity

        diversity_sum = sum(diversity_values.values())

        if diversity_sum == 0:
            for col in cols:
                internal_weights[col] = 1 / len(cols)
        else:
            for col in cols:
                internal_weights[col] = (
                    diversity_values[col] / diversity_sum
                )

        category_final = {
            col: internal_weights[col] * category_total
            for col in cols
        }

        # 차량보유 지표 상한 적용
        if CAR_INDICATOR in cols:
            car_weight = category_final[CAR_INDICATOR]

            if car_weight > CAR_CAP_TOTAL:
                excess = car_weight - CAR_CAP_TOTAL
                category_final[CAR_INDICATOR] = CAR_CAP_TOTAL

                others = [
                    c for c in cols
                    if c != CAR_INDICATOR
                ]

                other_sum = sum(category_final[c] for c in others)

                for c in others:
                    category_final[c] += (
                        excess * category_final[c] / other_sum
                    )

        for col in cols:
            final_weights[col] = category_final[col]

            entropy_rows.append({
                "대분류": category,
                "지표명": col,
                "유효표본수": E[col].notna().sum(),
                "다양성": diversity_values[col],
                "대분류내부가중치": internal_weights[col],
                "대분류가중치": category_total,
                "최종가중치": category_final[col]
            })

    return pd.DataFrame(entropy_rows), final_weights

# ----------------------------------------------------------
# 7. TOPSIS 계산 함수
# ----------------------------------------------------------
def run_topsis(final_weights, include_bus, include_rail):

    use_indicators = []

    for col in indicator_names:

        if col == TOTAL_ROUTE:
            continue

        if col == BUS_ROUTE and not include_bus:
            continue

        if col == RAIL_ROUTE and not include_rail:
            continue

        use_indicators.append(col)

    weighted_matrix = T_normalized[use_indicators].copy()

    for col in use_indicators:
        weighted_matrix[col] = (
            T_normalized[col] *
            A[col] *
            final_weights[col]
        )

    ideal_best = weighted_matrix[use_indicators].max()
    ideal_worst = weighted_matrix[use_indicators].min()

    distance_best = np.sqrt(
        ((weighted_matrix[use_indicators] - ideal_best) ** 2).sum(axis=1)
    )

    distance_worst = np.sqrt(
        ((weighted_matrix[use_indicators] - ideal_worst) ** 2).sum(axis=1)
    )

    closeness = distance_worst / (
        distance_best + distance_worst
    )

    result = pd.DataFrame({
        "도": T["도"],
        "시군구": T["시군구"],
        "취약도_CC": closeness
    })

    result = result.sort_values(
        "취약도_CC",
        ascending=False
    ).reset_index(drop=True)

    result["순위"] = result.index + 1

    return result, weighted_matrix

