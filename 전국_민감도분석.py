# ----------------------------------------------------------
# 6. 엔트로피 가중치 계산 함수
# ----------------------------------------------------------
def calculate_entropy_weights(include_car=True):

    final_weights = {}
    entropy_rows = []

    for category, cols in categories.items():

        # 차량보유 지표 제외 시나리오
        if not include_car:
            cols = [
                col for col in cols
                if col != CAR_INDICATOR
            ]

        category_total = category_weights[category]

        diversity_values = {}
        internal_weights = {}

        for col in cols:
            x = E[col].astype(float).dropna()

            if len(x) < 2:
                diversity_values[col] = 0.0
                internal_weights[col] = 0.0
                continue

            p = x / x.sum()
            p = p.replace(0, 1e-12)

            n = len(x)
            k = 1 / np.log(n)

            entropy = -(p * np.log(p)).sum() * k
            diversity = 1 - entropy

            diversity_values[col] = diversity

        diversity_sum = sum(diversity_values.values())

        if diversity_sum == 0:
            for col in cols:
                internal_weights[col] = 1 / len(cols)
        else:
            for col in cols:
                internal_weights[col] = (
                    diversity_values[col] / diversity_sum
                )

        category_final = {
            col: internal_weights[col] * category_total
            for col in cols
        }

        for col in cols:
            final_weights[col] = category_final[col]

            entropy_rows.append({
                "대분류": category,
                "지표명": col,
                "유효표본수": E[col].notna().sum(),
                "다양성": diversity_values[col],
                "대분류내부가중치": internal_weights[col],
                "대분류가중치": category_total,
                "최종가중치": category_final[col]
            })

    return pd.DataFrame(entropy_rows), final_weights

# ----------------------------------------------------------
# 7. TOPSIS 계산 함수
# ----------------------------------------------------------
def run_topsis(final_weights, include_car=True):

    use_indicators = [
        col for col in indicator_names
        if include_car or col != CAR_INDICATOR
    ]

    weighted_matrix = T_normalized[use_indicators].copy()

    for col in use_indicators:
        weighted_matrix[col] = (
            T_normalized[col] *
            A[col] *
            final_weights[col]
        )

    ideal_best = weighted_matrix[use_indicators].max()
    ideal_worst = weighted_matrix[use_indicators].min()

    distance_best = np.sqrt(
        ((weighted_matrix[use_indicators] - ideal_best) ** 2).sum(axis=1)
    )

    distance_worst = np.sqrt(
        ((weighted_matrix[use_indicators] - ideal_worst) ** 2).sum(axis=1)
    )

    closeness = distance_worst / (
        distance_best + distance_worst
    )

    result = pd.DataFrame({
        "도": T["도"],
        "시군구": T["시군구"],
        "취약도_CC": closeness
    })

    result = result.sort_values(
        "취약도_CC",
        ascending=False
    ).reset_index(drop=True)

    result["순위"] = result.index + 1

    return result, weighted_matrix

