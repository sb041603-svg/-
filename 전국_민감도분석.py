def apply_car_cap(weight_result, final_weights, car_share_in_a):

    final_weights = final_weights.copy()

    if car_share_in_a is None:
        return weight_result, final_weights

    car_cap_total = (
        category_weights["A_교통약자"] * car_share_in_a
    )

    car_weight = final_weights[CAR_INDICATOR]

    if car_weight > car_cap_total:
        excess = car_weight - car_cap_total
        final_weights[CAR_INDICATOR] = car_cap_total

        others = [
            col for col in categories["A_교통약자"]
            if col != CAR_INDICATOR
        ]

        other_sum = sum(final_weights[col] for col in others)

        for col in others:
            final_weights[col] += (
                excess * final_weights[col] / other_sum
            )

    # 엔트로피 결과표도 갱신
    weight_result = weight_result.copy()

    for col in categories["A_교통약자"]:
        weight_result.loc[
            weight_result["지표명"] == col,
            "최종가중치"
        ] = final_weights[col]

    return weight_result, final_weights

