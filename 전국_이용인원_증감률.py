data_list = []

for filename in uploaded.keys():

    # 엑셀파일만 읽기
    if not filename.lower().endswith((".xlsx", ".xls")):
        print(f"엑셀파일이 아니므로 제외합니다: {filename}")
        continue

    try:
        excel_file = pd.ExcelFile(filename)

        # 상세결과 시트가 있으면 사용
        if "상세결과" in excel_file.sheet_names:
            sheet_name = "상세결과"
        else:
            # 상세결과 시트가 없으면 첫 번째 시트 사용
            sheet_name = excel_file.sheet_names[0]

            print(
                f"주의: {filename}에 '상세결과' 시트가 없어 "
                f"'{sheet_name}' 시트를 사용합니다."
            )

        df = pd.read_excel(
            filename,
            sheet_name=sheet_name
        )

        # 열 이름 공백 제거
        df.columns = (
            df.columns
            .astype(str)
            .str.strip()
        )

        # 지역명과 원본파일명 추가
        df["분석지역"] = get_region(filename)
        df["원본파일"] = filename

        data_list.append(df)

        print(
            f"읽기 완료: {filename} / "
            f"{len(df):,}행 / "
            f"{get_region(filename)}"
        )

    except Exception as e:
        print(f"\n파일 읽기 오류: {filename}")
        print(e)

# 읽힌 파일이 없으면 중단
if len(data_list) == 0:
    raise ValueError(
        "읽을 수 있는 엑셀파일이 없습니다."
    )

# ============================================================
# 4. 7개 지역 데이터 통합
# ============================================================

all_data = pd.concat(
    data_list,
    ignore_index=True
)

print("\n통합 데이터 열 이름")
print(all_data.columns.tolist())

# 고속버스 분석에 필요한 필수 열
required_columns = [
    "연도",
    "도착지",
    "월~일합계"
]

missing_columns = [
    column
    for column in required_columns
    if column not in all_data.columns
]

if missing_columns:
    raise ValueError(
        f"다음 필수 열이 없습니다: {missing_columns}\n"
        f"현재 열 이름: {all_data.columns.tolist()}"
    )

# ============================================================
# 5. 데이터 정리
# ============================================================

# 연도 숫자화
all_data["연도"] = pd.to_numeric(
    all_data["연도"],
    errors="coerce"
)

# 이용자 수 숫자화
all_data["월~일합계"] = pd.to_numeric(
    all_data["월~일합계"],
    errors="coerce"
).fillna(0)

# 문자형 열 공백 제거
all_data["도착지"] = (
    all_data["도착지"]
    .astype(str)
    .str.strip()
)

all_data["분석지역"] = (
    all_data["분석지역"]
    .astype(str)
    .str.strip()
)

# 도착터미널_통일 열이 있으면 문자형으로 정리
if "도착터미널_통일" in all_data.columns:
    all_data["도착터미널_통일"] = (
        all_data["도착터미널_통일"]
        .astype(str)
        .str.strip()
    )

# 연도가 없는 행 제거
all_data = all_data.dropna(
    subset=["연도"]
)

all_data["연도"] = (
    all_data["연도"]
    .astype(int)
)

# ============================================================
# 6. 도착터미널 기준 만들기
# ============================================================

# 예시 파일처럼 도착터미널_통일 열이 있으면 사용
if "도착터미널_통일" in all_data.columns:

    all_data["분석터미널"] = (
        all_data["도착터미널_통일"]
        .astype(str)
        .str.strip()
    )

else:
    # 통일 열이 없으면 도착지 열을 사용
    all_data["분석터미널"] = (
        all_data["도착지"]
        .astype(str)
        .str.strip()
    )

# 터미널명 표기 통일
terminal_replace = {
    "동서울": "동서울터미널",
    "동서울종합터미널": "동서울터미널",
    "동서울터미널": "동서울터미널",

    "서울고속": "서울고속터미널",
    "서울(경부)": "서울고속터미널",
    "서울고속터미널": "서울고속터미널"
}

all_data["분석터미널"] = (
    all_data["분석터미널"]
    .replace(terminal_replace)
)

target_terminals = [
    "동서울터미널",
    "서울고속터미널"
]

# ============================================================
# 7. 지역별·연도별 전체 고속버스 이용자 합계
# ============================================================

region_year_total = (
    all_data
    .groupby(
        ["분석지역", "연도"],
        as_index=False
    )["월~일합계"]
    .sum()
    .rename(
        columns={
            "월~일합계": "고속버스이용자수"
        }
    )
    .sort_values(
        ["분석지역", "연도"]
    )
    .reset_index(drop=True)
)

# ============================================================
# 8. 지역별 전년 대비 증감 계산
# ============================================================

region_year_total["전년이용자수"] = (
    region_year_total
    .groupby("분석지역")["고속버스이용자수"]
    .shift(1)
)

region_year_total["증감인원"] = (
    region_year_total["고속버스이용자수"]
    - region_year_total["전년이용자수"]
)

region_year_total["증감률(%)"] = np.nan

compare_mask = (
    region_year_total["전년이용자수"].notna()
    &
    (region_year_total["전년이용자수"] != 0)
)

region_year_total.loc[
    compare_mask,
    "증감률(%)"
] = (
    region_year_total.loc[
        compare_mask,
        "증감인원"
    ]
    /
    region_year_total.loc[
        compare_mask,
        "전년이용자수"
    ]
    *
    100
)

region_year_total["증가여부"] = "확인필요"

region_year_total.loc[
    region_year_total["전년이용자수"].isna(),
    "증가여부"
] = "비교불가"

region_year_total.loc[
    region_year_total["증감인원"] > 0,
    "증가여부"
] = "증가"

region_year_total.loc[
    region_year_total["증감인원"] < 0,
    "증가여부"
] = "감소"

region_year_total.loc[
    region_year_total["증감인원"] == 0,
    "증가여부"
] = "동일"

region_year_total["증감률(%)"] = (
    region_year_total["증감률(%)"]
    .round(2)
)

# ============================================================
# 9. 지역별 매년 증가 여부 요약
# ============================================================

increase_summary = (
    region_year_total
    .groupby("분석지역")
    .agg(
        분석시작연도=("연도", "min"),
        분석종료연도=("연도", "max"),
        비교연도수=(
            "증감인원",
            lambda x: x.notna().sum()
        ),
        증가횟수=(
            "증가여부",
            lambda x: (x == "증가").sum()
        ),
        감소횟수=(
            "증가여부",
            lambda x: (x == "감소").sum()
        ),
        동일횟수=(
            "증가여부",
            lambda x: (x == "동일").sum()
        )
    )
    .reset_index()
)

increase_summary["매년증가여부"] = np.select(
    [
        increase_summary["비교연도수"] == 0,
        increase_summary["감소횟수"] > 0,
        increase_summary["동일횟수"] > 0
    ],
    [
        "비교불가",
        "아니오",
        "아니오"
    ],
    default="예"
)

# ============================================================
# 10. 지역·연도·도착터미널별 이용자 합계
# ============================================================

terminal_year_total = (
    all_data
    .groupby(
        ["분석지역", "연도", "분석터미널"],
        as_index=False
    )["월~일합계"]
    .sum()
    .rename(
        columns={
            "분석터미널": "도착터미널",
            "월~일합계": "터미널이용자수"
        }
    )
    .sort_values(
        ["분석지역", "도착터미널", "연도"]
    )
    .reset_index(drop=True)
)

# ============================================================
# 11. 터미널별 전년 대비 증감
# ============================================================

terminal_change = terminal_year_total.copy()

terminal_change["전년이용자수"] = (
    terminal_change
    .groupby(
        ["분석지역", "도착터미널"]
    )["터미널이용자수"]
    .shift(1)
)

terminal_change["증감인원"] = (
    terminal_change["터미널이용자수"]
    - terminal_change["전년이용자수"]
)

terminal_change["증감률(%)"] = np.nan

terminal_compare_mask = (
    terminal_change["전년이용자수"].notna()
    &
    (terminal_change["전년이용자수"] != 0)
)

terminal_change.loc[
    terminal_compare_mask,
    "증감률(%)"
] = (
    terminal_change.loc[
        terminal_compare_mask,
        "증감인원"
    ]
    /
    terminal_change.loc[
        terminal_compare_mask,
        "전년이용자수"
    ]
    *
    100
)

terminal_change["증가여부"] = "확인필요"

terminal_change.loc[
    terminal_change["전년이용자수"].isna(),
    "증가여부"
] = "비교불가"

terminal_change.loc[
    terminal_change["증감인원"] > 0,
    "증가여부"
] = "증가"

terminal_change.loc[
    terminal_change["증감인원"] < 0,
    "증가여부"
] = "감소"

terminal_change.loc[
    terminal_change["증감인원"] == 0,
    "증가여부"
] = "동일"

terminal_change["증감률(%)"] = (
    terminal_change["증감률(%)"]
    .round(2)
)

# ============================================================
# 12. 2개 서울권 터미널 자료만 필터링
# ============================================================

three_terminal_data = all_data[
    all_data["분석터미널"].isin(target_terminals)
].copy()

terminal_rank_total = (
    three_terminal_data
    .groupby(
        ["분석지역", "연도", "분석터미널"],
        as_index=False
    )["월~일합계"]
    .sum()
    .rename(
        columns={
            "분석터미널": "도착터미널",
            "월~일합계": "터미널이용자수"
        }
    )
)

# ============================================================
# 13. 지역·연도별 2개 터미널 순위
# ============================================================

terminal_rank_total["순위"] = (
    terminal_rank_total
    .groupby(
        ["분석지역", "연도"]
    )["터미널이용자수"]
    .rank(
        method="min",
        ascending=False
    )
    .astype(int)
)

terminal_rank = (
    terminal_rank_total
    .sort_values(
        ["분석지역", "연도", "순위", "도착터미널"]
    )
    .reset_index(drop=True)
)

# ============================================================
# 14. 연도별 지역 최다 이용 터미널
# ============================================================

top_terminal = (
    terminal_rank[
        terminal_rank["순위"] == 1
    ]
    .sort_values(
        ["분석지역", "연도"]
    )
    .reset_index(drop=True)
)

# ============================================================
# 15. 분석기간 전체 기준 지역별 터미널 순위
# ============================================================

terminal_region_total = (
    three_terminal_data
    .groupby(
        ["분석지역", "분석터미널"],
        as_index=False
    )["월~일합계"]
    .sum()
    .rename(
        columns={
            "분석터미널": "도착터미널",
            "월~일합계": "전체이용자수"
        }
    )
)

terminal_region_total["전체순위"] = (
    terminal_region_total
    .groupby("분석지역")["전체이용자수"]
    .rank(
        method="min",
        ascending=False
    )
    .astype(int)
)

terminal_region_rank = (
    terminal_region_total
    .sort_values(
        ["분석지역", "전체순위", "도착터미널"]
    )
    .reset_index(drop=True)
)

# ============================================================
# 16. 모든 지역을 합친 연도별 고속버스 추이
# ============================================================

national_year_total = (
    all_data
    .groupby(
        "연도",
        as_index=False
    )["월~일합계"]
    .sum()
    .rename(
        columns={
            "월~일합계": "전체고속버스이용자수"
        }
    )
    .sort_values("연도")
    .reset_index(drop=True)
)

national_year_total["전년이용자수"] = (
    national_year_total["전체고속버스이용자수"]
    .shift(1)
)

national_year_total["증감인원"] = (
    national_year_total["전체고속버스이용자수"]
    - national_year_total["전년이용자수"]
)

national_year_total["증감률(%)"] = np.nan

national_compare_mask = (
    national_year_total["전년이용자수"].notna()
    &
    (national_year_total["전년이용자수"] != 0)
)

national_year_total.loc[
    national_compare_mask,
    "증감률(%)"
] = (
    national_year_total.loc[
        national_compare_mask,
        "증감인원"
    ]
    /
    national_year_total.loc[
        national_compare_mask,
        "전년이용자수"
    ]
    *
    100
)

national_year_total["증가여부"] = "확인필요"

national_year_total.loc[
    national_year_total["전년이용자수"].isna(),
    "증가여부"
] = "비교불가"

national_year_total.loc[
    national_year_total["증감인원"] > 0,
    "증가여부"
] = "증가"

national_year_total.loc[
    national_year_total["증감인원"] < 0,
    "증가여부"
] = "감소"

national_year_total.loc[
    national_year_total["증감인원"] == 0,
    "증가여부"
] = "동일"

national_year_total["증감률(%)"] = (
    national_year_total["증감률(%)"]
    .round(2)
)

# ============================================================
# 17. 하나의 엑셀파일에 여러 시트로 저장
# ============================================================

output_file = "고속버스_7개도_통합분석결과.xlsx"

with pd.ExcelWriter(
    output_file,
    engine="openpyxl"
) as writer:

    all_data.to_excel(
        writer,
        sheet_name="전체원자료",
        index=False
    )

    region_year_total.to_excel(
        writer,
        sheet_name="지역별연도합계",
        index=False
    )

    increase_summary.to_excel(
        writer,
        sheet_name="고속버스증가여부요약",
        index=False
    )

    terminal_year_total.to_excel(
        writer,
        sheet_name="터미널별연도합계",
        index=False
    )

    terminal_change.to_excel(
        writer,
        sheet_name="터미널별증감",
        index=False
    )

    terminal_rank.to_excel(
        writer,
        sheet_name="2개터미널순위",
        index=False
    )

    top_terminal.to_excel(
        writer,
        sheet_name="연도별최다터미널",
        index=False
    )

    terminal_region_rank.to_excel(
        writer,
        sheet_name="지역별터미널순위",
        index=False
    )

    national_year_total.to_excel(
        writer,
        sheet_name="전국연도별추이",
        index=False
    )

print("\n고속버스 분석이 완료되었습니다.")
print(f"결과 파일명: {output_file}")

