# 전라북도 계층형 엔트로피 가중치 + 가용성 가중 TOPSIS
# 입력: 엔트로피용 값 / TOPSIS용 값 / TOPSIS용 가중치가 있는 엑셀
# ==========================================================

import pandas as pd
import numpy as np
import os
from google.colab import files

# ----------------------------------------------------------
# 1. 분석준비 엑셀 업로드
# ----------------------------------------------------------
print("엔트로피-TOPSIS 분석준비 엑셀 파일을 업로드하세요.")
uploaded = files.upload()

INPUT_FILE = list(uploaded.keys())[0]

BASE_NAME = os.path.splitext(INPUT_FILE)[0]
OUTPUT_FILE = BASE_NAME + "_취약지역_선정_결과.xlsx"

# ----------------------------------------------------------
# 2. 시트 읽기
# ----------------------------------------------------------
ENTROPY_SHEET = "04_엔트로피용_값"
TOPSIS_VALUE_SHEET = "05_TOPSIS용_값"
TOPSIS_WEIGHT_SHEET = "06_TOPSIS용_가중치"
FLAG_SHEET = "02_부재플래그_02"

entropy_df = pd.read_excel(INPUT_FILE, sheet_name=ENTROPY_SHEET)
topsis_df = pd.read_excel(INPUT_FILE, sheet_name=TOPSIS_VALUE_SHEET)
weight_df = pd.read_excel(INPUT_FILE, sheet_name=TOPSIS_WEIGHT_SHEET)
flag_df = pd.read_excel(INPUT_FILE, sheet_name=FLAG_SHEET)

# ----------------------------------------------------------
# 3. 대분류 및 지표 설정
# ----------------------------------------------------------
category_weights = {
    "A_교통약자": 0.40,
    "B_교통쇠퇴": 0.30,
    "C_서울접근성": 0.30
}

categories = {
    "A_교통약자": [
        "노인인구_전체인구비율(%)",
        "장애인구_전체인구비율(%)",
        "차량대수_전체인구비율"
    ],
    "B_교통쇠퇴": [
        "순만족도비율(%)",
        "버스_이용인원누적증감률_유효연도(%)",
        "철도_이용인원누적증감률_유효연도(%)",
        "노선수누적증감률_버스_유효연도(%)",
        "노선수누적증감률_철도_유효연도(%)",
        "운행횟수누적증감률_버스_유효연도(%)",
        "운행횟수누적증감률_철도_유효연도(%)"
    ],
    "C_서울접근성": [
        "서울직행_노선수_전체인구비율",
        "서울직행_운행횟수_전체인구비율"
    ]
}

# 차량보유 지표: A 대분류 40% 중 5%
# 즉, 전체 가중치 기준 최대 2%
CAR_INDICATOR = "차량대수_전체인구비율"
CAR_SHARE_IN_A = 0.05
CAR_CAP_TOTAL = category_weights["A_교통약자"] * CAR_SHARE_IN_A

# ----------------------------------------------------------
# 4. 지표 자동 추출
# ----------------------------------------------------------
entropy_columns = [
    col for col in entropy_df.columns
    if col.endswith("_엔트로피값")
]

indicators = []

for col in entropy_columns:
    base_name = col.replace("_엔트로피값", "")

    topsis_col = base_name + "_TOPSIS값"
    weight_col = base_name + "_TOPSIS가중치"
    flag_col = base_name + "_부재플래그"

    if topsis_col not in topsis_df.columns:
        raise ValueError(f"TOPSIS용 값 열이 없습니다: {topsis_col}")

    if weight_col not in weight_df.columns:
        raise ValueError(f"TOPSIS용 가중치 열이 없습니다: {weight_col}")

    if flag_col not in flag_df.columns:
        raise ValueError(f"부재플래그 열이 없습니다: {flag_col}")

    indicators.append({
        "base_name": base_name,
        "entropy_col": col,
        "topsis_col": topsis_col,
        "weight_col": weight_col,
        "flag_col": flag_col
    })

indicator_names = [item["base_name"] for item in indicators]

# 대분류에 없는 지표 확인
all_defined = sum(categories.values(), [])
missing = set(indicator_names) - set(all_defined)

if missing:
    raise ValueError(f"대분류에 포함되지 않은 지표가 있습니다: {missing}")

# ----------------------------------------------------------
# 5. 엔트로피용 값 및 TOPSIS용 값 행렬 생성
# ----------------------------------------------------------
E = entropy_df[["도", "시군구"] + entropy_columns].copy()
T = topsis_df[["도", "시군구"] + [i["topsis_col"] for i in indicators]].copy()
A = weight_df[["도", "시군구"] + [i["weight_col"] for i in indicators]].copy()
S = flag_df[["도", "시군구"] + [i["flag_col"] for i in indicators]].copy()

E.columns = ["도", "시군구"] + indicator_names
T.columns = ["도", "시군구"] + indicator_names
A.columns = ["도", "시군구"] + indicator_names
S.columns = ["도", "시군구"] + indicator_names

# ----------------------------------------------------------
# 6. TOPSIS용 값 min-max 정규화
# 이미 역방향 전환이 완료되었으므로 값이 클수록 취약
# ----------------------------------------------------------
T_normalized = T.copy()

for col in indicator_names:
    x = T[col].astype(float)
    xmin = x.min()
    xmax = x.max()

    if xmax == xmin:
        T_normalized[col] = 0.5
    else:
        T_normalized[col] = (x - xmin) / (xmax - xmin)

# ----------------------------------------------------------
# 7. 대분류 내부 엔트로피 가중치 계산
# 엔트로피는 실제값만 사용, 결측은 제외
# ----------------------------------------------------------
entropy_rows = []
final_weights = {}

for category, cols in categories.items():

    category_total = category_weights[category]

    entropy_values = {}
    diversity_values = {}
    internal_weights = {}

    for col in cols:
        x = E[col].astype(float).dropna()

        # 유효 표본이 2개 미만이면 가중치 0
        if len(x) < 2:
            entropy_values[col] = np.nan
            diversity_values[col] = 0.0
            internal_weights[col] = 0.0
            continue

        p = x / x.sum()
        p = p.replace(0, 1e-12)

        n = len(x)
        k = 1 / np.log(n)

        entropy = -(p * np.log(p)).sum() * k
        diversity = 1 - entropy

        entropy_values[col] = entropy
        diversity_values[col] = diversity

    # 다양성 합이 0이면 균등 가중치
    diversity_sum = sum(diversity_values.values())

    if diversity_sum == 0:
        for col in cols:
            internal_weights[col] = 1 / len(cols)
    else:
        for col in cols:
            internal_weights[col] = diversity_values[col] / diversity_sum

    # 대분류 내부 가중치를 전체 가중치로 환산
    category_final = {
        col: internal_weights[col] * category_total
        for col in cols
    }

    # 차량보유 지표 상한 적용
    if CAR_INDICATOR in cols:
        car_weight = category_final[CAR_INDICATOR]

        if car_weight > CAR_CAP_TOTAL:
            excess = car_weight - CAR_CAP_TOTAL
            category_final[CAR_INDICATOR] = CAR_CAP_TOTAL

            others = [
                col for col in cols
                if col != CAR_INDICATOR
            ]

            other_sum = sum(category_final[col] for col in others)

            for col in others:
                category_final[col] += (
                    excess * category_final[col] / other_sum
                )

    for col in cols:
        final_weights[col] = category_final[col]

        entropy_rows.append({
            "대분류": category,
            "지표명": col,
            "유효표본수": E[col].notna().sum(),
            "엔트로피": entropy_values[col],
            "다양성": diversity_values[col],
            "대분류내부가중치": internal_weights[col],
            "대분류가중치": category_total,
            "최종가중치": category_final[col]
        })

weight_result = pd.DataFrame(entropy_rows)

# ----------------------------------------------------------
# 8. 가용성 가중 TOPSIS
# ----------------------------------------------------------
weighted_matrix = T_normalized[indicator_names].copy()

for col in indicator_names:
    weighted_matrix[col] = (
        T_normalized[col] *
        A[col] *
        final_weights[col]
    )

ideal_best = weighted_matrix[indicator_names].max()
ideal_worst = weighted_matrix[indicator_names].min()

distance_best = np.sqrt(
    ((weighted_matrix[indicator_names] - ideal_best) ** 2).sum(axis=1)
)

distance_worst = np.sqrt(
    ((weighted_matrix[indicator_names] - ideal_worst) ** 2).sum(axis=1)
)

closeness = distance_worst / (distance_best + distance_worst)

result = pd.DataFrame({
    "도": T["도"],
    "시군구": T["시군구"],
    "취약도_CC": closeness,
    "취약도_백분율": closeness * 100
})

result = result.sort_values("취약도_CC", ascending=False).reset_index(drop=True)
result["순위"] = result.index + 1

result["취약등급"] = pd.qcut(
    result["취약도_CC"],
    q=3,
    labels=["낮음", "중간", "높음"]
)

# ----------------------------------------------------------
# 9. 수식 설명 시트
# ----------------------------------------------------------
formula_df = pd.DataFrame([
    ["1. 대분류 가중치", "A=40%, B=30%, C=30%", "연구자가 설정한 상위 가중치"],
    ["2. 대분류 내부 엔트로피", "e_j = -k Σ p_ij ln(p_ij)", "실제값이 있는 지역만 대상으로 계산"],
    ["3. 비율 행렬", "p_ij = x_ij / Σ x_ij", "각 지표 내 시군별 비율"],
    ["4. 엔트로피 상수", "k = 1 / ln(n)", "n은 유효 표본 수"],
    ["5. 다양성", "d_j = 1 - e_j", "엔트로피가 낮을수록 지역 간 차이가 큼"],
    ["6. 대분류 내부 가중치", "w_j_internal = d_j / Σd_j", "대분류 내부 상대적 중요도"],
    ["7. 최종 엔트로피 가중치", "w_j = w_j_internal × 대분류가중치", "예: A 내부 0.30 × 40% = 전체 12%"],
    ["8. 차량보유 상한", "차량지표 최종가중치 ≤ 2%", "A 대분류 40% 중 5%만 반영"],
    ["9. 상한 초과분 배분", "초과분을 A 내 다른 지표에 비례 배분", "차량 지표의 과도한 영향력 방지"],
    ["10. TOPSIS용 값", "실제값 또는 중립값 0.5", "결측 지역도 완전히 배제하지 않음"],
    ["11. 부재 상태 가중치", "a_ij = 06_TOPSIS용_가중치", "자료 있음 1.0, 자료 없음 0.5"],
    ["12. TOPSIS 가중행렬", "v_ij = w_j × a_ij × x'_ij", "계층형 엔트로피 가중치와 부재 가중치를 함께 반영"],
    ["13. 긍정 이상해", "A+ = max_i(v_ij)", "가장 취약한 값"],
    ["14. 부정 이상해", "A- = min_i(v_ij)", "가장 덜 취약한 값"],
    ["15. 거리", "D+ = sqrt(Σ(v-A+)^2), D- = sqrt(Σ(v-A-)^2)", "이상해와의 거리"],
    ["16. TOPSIS 점수", "CC = D- / (D+ + D-)", "값이 클수록 취약지역"]
], columns=["단계", "수식", "설명"])

# ----------------------------------------------------------
# 10. 엑셀 저장
# ----------------------------------------------------------
with pd.ExcelWriter(OUTPUT_FILE, engine="openpyxl") as writer:
    result.to_excel(
        writer,
        sheet_name="01_TOPSIS_취약지역_순위",
        index=False
    )

    weight_result.to_excel(
        writer,
        sheet_name="02_계층형엔트로피_가중치",
        index=False
    )

    formula_df.to_excel(
        writer,
        sheet_name="03_수식_및_계산과정",
        index=False
    )

    T_normalized.to_excel(
        writer,
        sheet_name="04_TOPSIS_정규화행렬",
        index=False
    )

    A.to_excel(
        writer,
        sheet_name="05_부재상태_가중치",
        index=False
    )

    weighted_matrix.to_excel(
        writer,
        sheet_name="06_TOPSIS_가중행렬",
        index=False
    )

    distance_result = T[["도", "시군구"]].copy()
    distance_result["D+_긍정이상해거리"] = distance_best.values
    distance_result["D-_부정이상해거리"] = distance_worst.values
    distance_result["TOPSIS_CC"] = closeness.values

    distance_result.to_excel(
        writer,
        sheet_name="07_TOPSIS_거리계산",
        index=False
    )

# ----------------------------------------------------------
# 11. 결과 출력 및 다운로드
# ----------------------------------------------------------
print("\n===== 대분류별 최종 가중치 합계 =====")
print(
    weight_result
    .groupby("대분류")["최종가중치"]
    .sum()
    .to_string()
)

print("\n===== 지표별 최종 가중치 =====")
print(
    weight_result[["대분류", "지표명", "최종가중치"]]
    .sort_values("최종가중치", ascending=False)
    .to_string(index=False)
)

print("\n===== 취약지역 순위 =====")
print(result.to_string(index=False))

files.download(OUTPUT_FILE)

