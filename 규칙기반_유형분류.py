# -----------------------------
# 2. 지표가 어느 대분류에 속하는지 판별
# -----------------------------

def classify_column(col):
    col_clean = str(col).strip()

    # 서울접근성 우선 판별
    for keyword in CATEGORY_RULES["C_서울접근성"]:
        if keyword in col_clean:
            return "C_서울접근성"

    # 교통쇠퇴
    for keyword in CATEGORY_RULES["B_교통쇠퇴"]:
        if keyword in col_clean:
            return "B_교통쇠퇴"

    # 교통약자
    for keyword in CATEGORY_RULES["A_교통약자"]:
        if keyword in col_clean:
            return "A_교통약자"

    return None

# -----------------------------
# 3. 대분류 점수 계산 함수
# -----------------------------

def calculate_category_scores(norm_df, weight_df):

    result_rows = []

    for _, row in norm_df.iterrows():
        region = row["시군구"]
        province = row["도"]

        category_scores = {}
        category_detail = {}

        for category in CATEGORY_RULES.keys():

            category_cols = []
            weights = []

            for col in norm_df.columns:
                if col in ["도", "시군구"]:
                    continue

                if classify_column(col) == category:
                    value = row[col]

                    # 결측 제외
                    if pd.isna(value):
                        continue

                    # 해당 지표의 최종가중치 찾기
                    matched = weight_df[
                        weight_df["지표명"].str.strip() == col.strip()
                    ]

                    if len(matched) > 0:
                        weight = matched["최종가중치"].iloc[0]
                    else:
                        weight = 0.0

                    # 가중치가 0이면 균등가중치로 대체
                    if weight <= 0:
                        weight = 1.0

                    category_cols.append(col)
                    weights.append(weight)

            if len(category_cols) == 0:
                category_scores[category] = np.nan
                category_detail[category] = "해당 지표 없음"
                continue

            values = row[category_cols].astype(float).values
            weights = np.array(weights, dtype=float)

            score = np.sum(values * weights) / np.sum(weights)

            category_scores[category] = score

            # 해당 대분류에서 가장 취약한 지표
            max_idx = np.argmax(values)
            top_indicator = category_cols[max_idx]

            category_detail[category] = top_indicator

        result_rows.append({
            "도": province,
            "시군구": region,
            "A_교통약자_점수": category_scores.get("A_교통약자"),
            "B_교통쇠퇴_점수": category_scores.get("B_교통쇠퇴"),
            "C_서울접근성_점수": category_scores.get("C_서울접근성"),
            "A_최고취약지표": category_detail.get("A_교통약자"),
            "B_최고취약지표": category_detail.get("B_교통쇠퇴"),
            "C_최고취약지표": category_detail.get("C_서울접근성")
        })

    return pd.DataFrame(result_rows)

# -----------------------------
# 4. 규칙기반 유형 분류 함수
# -----------------------------

def rule_based_classification(df):

    df = df.copy()

    score_cols = [
        "A_교통약자_점수",
        "B_교통쇠퇴_점수",
        "C_서울접근성_점수"
    ]

    types = []
    main_categories = []

    for _, row in df.iterrows():

        scores = row[score_cols].astype(float)

        # 결측이 많으면 분류 불가
        if scores.isna().sum() >= 2:
            types.append("분류 불가")
            main_categories.append("판단 불가")
            continue

        max_category = scores.idxmax()

        if max_category == "A_교통약자_점수":
            main = "교통약자"
            category_type = "교통약자 집중형"

        elif max_category == "B_교통쇠퇴_점수":
            main = "교통쇠퇴"
            category_type = "교통서비스 쇠퇴형"

        else:
            main = "서울접근성"
            category_type = "서울 접근성 부족형"

        # 복합 취약형 판단
        # 세 영역 모두 해당 도 내 상위 기준 이상이면 복합형
        # 여기서는 단순하게 세 점수 모두 0.7 이상인 경우로 설정
        if (
            row["A_교통약자_점수"] >= 0.7
            and row["B_교통쇠퇴_점수"] >= 0.7
            and row["C_서울접근성_점수"] >= 0.7
        ):
            category_type = "복합 취약형"
            main = "복합"

        types.append(category_type)
        main_categories.append(main)

    df["최고취약영역"] = main_categories
    df["규칙기반_취약유형"] = types

    return df

