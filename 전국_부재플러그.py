# 지역별 엔트로피-TOPSIS 분석준비 엑셀 자동 생성
# 부재플래그: 0=노선있음·자료있음, 1=노선없음, 2=자료부재
# ==========================================================

import pandas as pd
import numpy as np
import os
from google.colab import files

# ----------------------------------------------------------
# 1. 원본 엑셀 업로드
# ----------------------------------------------------------
print("분석할 지역의 원본 엑셀 파일을 업로드하세요.")
uploaded = files.upload()

INPUT_FILE = list(uploaded.keys())[0]

# 출력 파일명: 업로드 파일명에서 확장자 제거 후 붙임
BASE_NAME = os.path.splitext(INPUT_FILE)[0]
OUTPUT_FILE = BASE_NAME + "_엔트로피TOPSIS_분석준비_개선판.xlsx"

# ----------------------------------------------------------
# 2. 시트 읽기
# ----------------------------------------------------------
VALUE_SHEET = "01_엔트로피분석용_시군별"
GTFS_SHEET = "보존_원자료_GTFS증감"

df = pd.read_excel(INPUT_FILE, sheet_name=VALUE_SHEET)
gtfs = pd.read_excel(INPUT_FILE, sheet_name=GTFS_SHEET)

# 해당 지역 시군만 추출
sigun_list = df["시군구"].tolist()
gtfs = gtfs[gtfs["시군구"].isin(sigun_list)].copy()

# ----------------------------------------------------------
# 3. 지표 설정
# ----------------------------------------------------------
# 높을수록 취약한 일반 지표
higher_vulnerable = [
    "노인인구_전체인구비율(%)",
    "장애인구_전체인구비율(%)",
    "차량대수_전체인구비율"
]

# 낮을수록 취약한 일반 지표
lower_vulnerable = [
    "순만족도비율(%)",
    "서울직행_노선수_전체인구비율",
    "서울직행_운행횟수_전체인구비율"
]

# 0/1/2 플래그를 적용할 교통 증감률 지표
# {최종 지표명: GTFS 원자료 기준 열}
transport_indicators = {
    "버스_이용인원누적증감률_유효연도(%)": "노선수_버스",
    "철도_이용인원누적증감률_유효연도(%)": "노선수_철도",
    "노선수누적증감률_버스_유효연도(%)": "노선수_버스",
    "노선수누적증감률_철도_유효연도(%)": "노선수_철도",
    "운행횟수누적증감률_버스_유효연도(%)": "일일운행횟수_버스",
    "운행횟수누적증감률_철도_유효연도(%)": "일일운행횟수_철도",

}

all_indicators = (
    higher_vulnerable +
    lower_vulnerable +
    list(transport_indicators.keys())
)

# ----------------------------------------------------------
# 4. 부재플래그 0/1/2 생성
# ----------------------------------------------------------
flag_df = pd.DataFrame({
    "도": df["도"],
    "시군구": df["시군구"]
})

for indicator, gtfs_col in transport_indicators.items():

    flags = []

    for i in df.index:
        sigun = df.loc[i, "시군구"]
        value = df.loc[i, indicator]

        # 해당 시군의 GTFS 원자료
        g = gtfs[gtfs["시군구"] == sigun]

        # 노선 또는 서비스 존재 여부
        has_service = (g[gtfs_col] > 0).any()

        if pd.notna(value):
            # 실제 데이터가 있음
            status = 0

        elif not has_service:
            # 노선 또는 서비스 자체가 없음
            status = 1

        else:
            # 자료가 없음
            status = 2

        flags.append(status)

    flag_df[indicator + "_부재플래그"] = flags

# 일반 지표: 값이 있으면 0, 결측이면 2
for col in higher_vulnerable + lower_vulnerable:
    flags = []

    for i in df.index:
        value = df.loc[i, col]

        if pd.notna(value):
            flags.append(0)
        else:
            flags.append(2)

    flag_df[col + "_부재플래그"] = flags

# ----------------------------------------------------------
# 5. 취약형 변환
# 모든 지표를 '값이 클수록 취약'으로 통일
# ----------------------------------------------------------
vuln_df = pd.DataFrame({
    "도": df["도"],
    "시군구": df["시군구"]
})

for col in all_indicators:

    if col in higher_vulnerable:
        # 이미 높을수록 취약
        vuln_df[col + "_취약형"] = df[col]

    elif col in lower_vulnerable:
        # 높을수록 좋은 지표이므로 부호 반전
        vuln_df[col + "_취약형"] = -df[col]

    elif col in transport_indicators:
        # 증감률이 낮거나 감소할수록 취약
        vuln_df[col + "_취약형"] = -df[col]

# ----------------------------------------------------------
# 6. 상태별 분석값 초안
# 0: 실제 취약형 값
# 1: 노선 없음 -> 1.0
# 2: 자료 부재 -> 0.5
# ----------------------------------------------------------
STATUS_WEIGHT = {
    0: 1.0,
    1: 0.8,
    2: 0.5
}

STATUS_VALUE = {
    0: "actual",
    1: 0.8,
    2: 0.5
}

analysis_value = pd.DataFrame({
    "도": df["도"],
    "시군구": df["시군구"]
})

availability_weight = pd.DataFrame({
    "도": df["도"],
    "시군구": df["시군구"]
})

for col in all_indicators:

    flag_col = col + "_부재플래그"
    vuln_col = col + "_취약형"

    values = []
    weights = []

    for i in df.index:
        status = flag_df.loc[i, flag_col]

        if col in transport_indicators:
            if status == 0:
                value = vuln_df.loc[i, vuln_col]
            elif status == 1:
                value = 0.8
            else:
                value = 0.5

        else:
            if status == 0:
                value = vuln_df.loc[i, vuln_col]
            elif status == 2:
                value = 0.5
            else:
                raise ValueError(
                    f"일반 지표에는 상태 1을 사용할 수 없습니다: {col}"
                )

        values.append(value)
        weights.append(STATUS_WEIGHT[status])

    analysis_value[col + "_분석값"] = values
    availability_weight[col + "_가중치"] = weights

# ----------------------------------------------------------
# 7. 엑셀 저장
# ----------------------------------------------------------
with pd.ExcelWriter(OUTPUT_FILE, engine="openpyxl") as writer:
    df.to_excel(
        writer,
        sheet_name="01_원본_지표값",
        index=False
    )

    flag_df.to_excel(
        writer,
        sheet_name="02_부재플래그_012",
        index=False
    )

    vuln_df.to_excel(
        writer,
        sheet_name="03_취약형_변환",
        index=False
    )

    analysis_value.to_excel(
        writer,
        sheet_name="04_상태별_분석값",
        index=False
    )

    availability_weight.to_excel(
        writer,
        sheet_name="05_상태별_가중치",
        index=False
    )

# ----------------------------------------------------------
# 8. 요약 출력 및 다운로드
# ----------------------------------------------------------
flag_cols = [c for c in flag_df.columns if "부재플래그" in c]

print("\n===== 부재플래그 0/1/2 분포 =====")
print(
    flag_df[flag_cols]
    .apply(pd.Series.value_counts)
    .fillna(0)
    .astype(int)
)

print(f"\n생성 완료: {OUTPUT_FILE}")

files.download(OUTPUT_FILE)

