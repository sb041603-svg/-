# ----------------------------------------------------------
# 3. 지표 설정
# ----------------------------------------------------------
higher_vulnerable = [
    "노인인구_전체인구비율(%)",
    "장애인구_전체인구비율(%)",
    "차량대수_전체인구비율"
]

lower_vulnerable = [
    "순만족도비율(%)",
    "서울직행_노선수_전체인구비율",
    "서울직행_운행횟수_전체인구비율"
]

transport_indicators = [
    "버스_이용인원누적증감률_유효연도(%)",
    "철도_이용인원누적증감률_유효연도(%)",
    "서울직행노선수누적증감률_유효연도(%)",
    "서울직행운행횟수누적증감률_유효연도(%)",
]

all_indicators = (
    higher_vulnerable +
    lower_vulnerable +
    transport_indicators
)

# ----------------------------------------------------------
# 4. 지역별 분석준비 엑셀 생성 함수
# ----------------------------------------------------------
def create_prep_excel(region_df, region_name):

    output_file = f"{region_name}_엔트로피TOPSIS_분석준비_개선판.xlsx"

    # ------------------------------------------------------
    # 4-1. 부재플래그 생성
    # 0 = 자료 있음
    # 2 = 자료 없음 또는 증감률 계산 불가
    # ------------------------------------------------------
    flag_df = pd.DataFrame({
        "도": region_df["도"],
        "시군구": region_df["시군구"]
    })

    for col in all_indicators:

        flags = []

        for i in region_df.index:
            value = region_df.loc[i, col]

            if pd.notna(value):
                flags.append(0)
            else:
                flags.append(2)

        flag_df[col + "_부재플래그"] = flags

    # ------------------------------------------------------
    # 4-2. 취약형 변환
    # 모든 지표를 값이 클수록 취약하도록 변환
    # ------------------------------------------------------
    vuln_df = pd.DataFrame({
        "도": region_df["도"],
        "시군구": region_df["시군구"]
    })

    for col in all_indicators:

        if col in higher_vulnerable:
            vuln_df[col + "_취약형"] = region_df[col]

        elif col in lower_vulnerable:
            vuln_df[col + "_취약형"] = -region_df[col]

        elif col in transport_indicators:
            vuln_df[col + "_취약형"] = -region_df[col]

    # ------------------------------------------------------
    # 4-3. 엔트로피용 값 및 TOPSIS용 값 생성
    # ------------------------------------------------------
    entropy_value = pd.DataFrame({
        "도": region_df["도"],
        "시군구": region_df["시군구"]
    })

    topsis_value = pd.DataFrame({
        "도": region_df["도"],
        "시군구": region_df["시군구"]
    })

    topsis_weight = pd.DataFrame({
        "도": region_df["도"],
        "시군구": region_df["시군구"]
    })

    for col in all_indicators:

        flag_col = col + "_부재플래그"
        vuln_col = col + "_취약형"

        entropy_values = []
        topsis_values = []
        weights = []

        for i in region_df.index:
            status = flag_df.loc[i, flag_col]
            actual_value = vuln_df.loc[i, vuln_col]

            if status == 0:
                entropy_values.append(actual_value)
                topsis_values.append(actual_value)
                weights.append(1.0)

            else:
                entropy_values.append(np.nan)
                topsis_values.append(0.5)
                weights.append(0.5)

        entropy_value[col + "_엔트로피값"] = entropy_values
        topsis_value[col + "_TOPSIS값"] = topsis_values
        topsis_weight[col + "_TOPSIS가중치"] = weights

    # ------------------------------------------------------
    # 4-4. 엑셀 저장
    # ------------------------------------------------------
    with pd.ExcelWriter(output_file, engine="openpyxl") as writer:

        region_df.to_excel(
            writer,
            sheet_name="01_원본_지표값",
            index=False
        )

        flag_df.to_excel(
            writer,
            sheet_name="02_부재플래그_02",
            index=False
        )

        vuln_df.to_excel(
            writer,
            sheet_name="03_취약형_변환",
            index=False
        )

        entropy_value.to_excel(
            writer,
            sheet_name="04_엔트로피용_값",
            index=False
        )

        topsis_value.to_excel(
            writer,
            sheet_name="05_TOPSIS용_값",
            index=False
        )

        topsis_weight.to_excel(
            writer,
            sheet_name="06_TOPSIS용_가중치",
            index=False
        )

    # ------------------------------------------------------
    # 4-5. 요약 출력
    # ------------------------------------------------------
    flag_cols = [
        col for col in flag_df.columns
        if "부재플래그" in col
    ]

    print(f"\n===== {region_name} 부재플래그 분포 =====")
    print(
        flag_df[flag_cols]
        .apply(pd.Series.value_counts)
        .fillna(0)
        .astype(int)
    )

