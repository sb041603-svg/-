# ==========================================================
# 강원도 엔트로피-TOPSIS 분석준비 엑셀 생성
# 부재플래그: 0=자료있음, 2=자료없음 또는 계산불가
# 엔트로피: 실제값만 사용
# TOPSIS: 결측은 중립값 0.5, 가중치 0.5
# ==========================================================

import pandas as pd
import numpy as np
import os
from google.colab import files

# ----------------------------------------------------------
# 1. 원본 엑셀 업로드
# ----------------------------------------------------------
print("강원도 원본 엑셀 파일을 업로드하세요.")
uploaded = files.upload()

INPUT_FILE = list(uploaded.keys())[0]

BASE_NAME = os.path.splitext(INPUT_FILE)[0]
OUTPUT_FILE = BASE_NAME + "_엔트로피TOPSIS_분석준비_개선판.xlsx"

# ----------------------------------------------------------
# 2. 시트 읽기
# ----------------------------------------------------------
VALUE_SHEET = "01_엔트로피분석용_시군별"
GTFS_SHEET = "보존_원자료_GTFS증감"

df = pd.read_excel(INPUT_FILE, sheet_name=VALUE_SHEET)
gtfs = pd.read_excel(INPUT_FILE, sheet_name=GTFS_SHEET)

sigun_list = df["시군구"].tolist()
gtfs = gtfs[gtfs["시군구"].isin(sigun_list)].copy()

# ----------------------------------------------------------
# 3. 지표 설정
# ----------------------------------------------------------
higher_vulnerable = [
    "노인인구_전체인구비율(%)",
    "장애인구_전체인구비율(%)",
    "차량대수_전체인구비율"
]

lower_vulnerable = [
    "순만족도비율(%)",
    "서울직행_노선수_전체인구비율",
    "서울직행_운행횟수_전체인구비율"
]

transport_indicators = {
    "버스_이용인원누적증감률_유효연도(%)": "노선수_버스",
    "철도_이용인원누적증감률_유효연도(%)": "노선수_철도",
    "노선수누적증감률_버스_유효연도(%)": "노선수_버스",
    "노선수누적증감률_철도_유효연도(%)": "노선수_철도",
    "노선수누적증감률_전체_유효연도(%)": "노선수_전체",
    "운행횟수누적증감률_버스_유효연도(%)": "일일운행횟수_버스",
    "운행횟수누적증감률_철도_유효연도(%)": "일일운행횟수_철도",
    "운행횟수누적증감률_전체_유효연도(%)": "일일운행횟수_전체"
}

all_indicators = (
    higher_vulnerable +
    lower_vulnerable +
    list(transport_indicators.keys())
)

# ----------------------------------------------------------
# 4. 부재플래그 생성
# 0 = 자료 있음
# 2 = 자료 없음 또는 증감률 계산 불가
# ----------------------------------------------------------
flag_df = pd.DataFrame({
    "도": df["도"],
    "시군구": df["시군구"]
})

for indicator, gtfs_col in transport_indicators.items():

    flags = []

    for i in df.index:
        sigun = df.loc[i, "시군구"]
        value = df.loc[i, indicator]

        g = gtfs[gtfs["시군구"] == sigun]

        has_service = (g[gtfs_col] > 0).any()

        if pd.notna(value):
            status = 0
        else:
            status = 2

        flags.append(status)

    flag_df[indicator + "_부재플래그"] = flags

for col in higher_vulnerable + lower_vulnerable:

    flags = []

    for i in df.index:
        value = df.loc[i, col]

        if pd.notna(value):
            flags.append(0)
        else:
            flags.append(2)

    flag_df[col + "_부재플래그"] = flags

# ----------------------------------------------------------
# 5. 취약형 변환
# 모든 지표를 값이 클수록 취약하도록 변환
# ----------------------------------------------------------
vuln_df = pd.DataFrame({
    "도": df["도"],
    "시군구": df["시군구"]
})

for col in all_indicators:

    if col in higher_vulnerable:
        vuln_df[col + "_취약형"] = df[col]

    elif col in lower_vulnerable:
        vuln_df[col + "_취약형"] = -df[col]

    elif col in transport_indicators:
        vuln_df[col + "_취약형"] = -df[col]

# ----------------------------------------------------------
# 6. 엔트로피용 값 및 TOPSIS용 값 분리 생성
# ----------------------------------------------------------
STATUS_WEIGHT = {
    0: 1.0,
    2: 0.5
}

entropy_value = pd.DataFrame({
    "도": df["도"],
    "시군구": df["시군구"]
})

topsis_value = pd.DataFrame({
    "도": df["도"],
    "시군구": df["시군구"]
})

topsis_weight = pd.DataFrame({
    "도": df["도"],
    "시군구": df["시군구"]
})

for col in all_indicators:

    flag_col = col + "_부재플래그"
    vuln_col = col + "_취약형"

    entropy_values = []
    topsis_values = []
    weights = []

    for i in df.index:
        status = flag_df.loc[i, flag_col]
        actual_value = vuln_df.loc[i, vuln_col]

        if status == 0:
            entropy_values.append(actual_value)
            topsis_values.append(actual_value)
            weights.append(1.0)

        else:
            entropy_values.append(np.nan)
            topsis_values.append(0.5)
            weights.append(0.5)

    entropy_value[col + "_엔트로피값"] = entropy_values
    topsis_value[col + "_TOPSIS값"] = topsis_values
    topsis_weight[col + "_TOPSIS가중치"] = weights

# ----------------------------------------------------------
# 7. 엑셀 저장
# ----------------------------------------------------------
with pd.ExcelWriter(OUTPUT_FILE, engine="openpyxl") as writer:

    df.to_excel(
        writer,
        sheet_name="01_원본_지표값",
        index=False
    )

    flag_df.to_excel(
        writer,
        sheet_name="02_부재플래그_02",
        index=False
    )

    vuln_df.to_excel(
        writer,
        sheet_name="03_취약형_변환",
        index=False
    )

    entropy_value.to_excel(
        writer,
        sheet_name="04_엔트로피용_값",
        index=False
    )

    topsis_value.to_excel(
        writer,
        sheet_name="05_TOPSIS용_값",
        index=False
    )

    topsis_weight.to_excel(
        writer,
        sheet_name="06_TOPSIS용_가중치",
        index=False
    )

# ----------------------------------------------------------
# 8. 요약 출력 및 다운로드
# ----------------------------------------------------------
flag_cols = [c for c in flag_df.columns if "부재플래그" in c]

print("\n===== 부재플래그 분포 =====")
print(
    flag_df[flag_cols]
    .apply(pd.Series.value_counts)
    .fillna(0)
    .astype(int)
)

print(f"\n생성 완료: {OUTPUT_FILE}")

files.download(OUTPUT_FILE)

